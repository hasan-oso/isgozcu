"""Filter Construction-PPE labels (11 classes) → İşGözcü v4 schema (6 classes).

Reads YOLO-format labels from `data/construction_ppe/{labels,images}/{train,val,test}/`
and writes:

    data/construction_ppe_filtered/
        ├── images/{train,val,test}/   (only images that still have ≥1 annotation)
        ├── labels/{train,val,test}/   (filtered + remapped YOLO labels)
        ├── data.yaml                  (Ultralytics-style dataset descriptor)
        └── stats.json                 (per-class instance counts per split)

Class mapping
-------------
Construction-PPE original ids:
    0: helmet, 1: gloves, 2: vest, 3: boots, 4: goggles, 5: none,
    6: Person, 7: no_helmet, 8: no_goggle, 9: no_gloves, 10: no_boots

İşGözcü v4 (6 classes, kept ones below):
    0: Person     ← original 6
    1: helmet     ← original 0
    2: vest       ← original 2
    3: gloves     ← original 1
    4: no_helmet  ← original 7
    5: no_gloves  ← original 9

Drop: 3 boots, 4 goggles, 5 none, 8 no_goggle, 10 no_boots.
"""

from __future__ import annotations

import json
import shutil
import sys
from collections import defaultdict
from pathlib import Path

# UTF-8 console for Turkish output
for _stream in (sys.stdout, sys.stderr):
    if hasattr(_stream, "reconfigure"):
        try:
            _stream.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass

PROJECT_ROOT = Path(__file__).resolve().parents[1]
SRC_ROOT = PROJECT_ROOT / "data" / "construction_ppe"
DST_ROOT = PROJECT_ROOT / "data" / "construction_ppe_filtered"
SPLITS = ("train", "val", "test")

# old_id → new_id; missing keys are dropped.
ID_REMAP: dict[int, int] = {
    6: 0,  # Person
    0: 1,  # helmet
    2: 2,  # vest
    1: 3,  # gloves
    7: 4,  # no_helmet
    9: 5,  # no_gloves
}

NEW_NAMES: dict[int, str] = {
    0: "Person",
    1: "helmet",
    2: "vest",
    3: "gloves",
    4: "no_helmet",
    5: "no_gloves",
}

# Original 11-class names — for stats logging only.
ORIG_NAMES: dict[int, str] = {
    0: "helmet",
    1: "gloves",
    2: "vest",
    3: "boots",
    4: "goggles",
    5: "none",
    6: "Person",
    7: "no_helmet",
    8: "no_goggle",
    9: "no_gloves",
    10: "no_boots",
}

MIN_TRAIN_SAMPLES_WARN = 100  # warn if a v4 class has fewer than this in train


# ---------- helpers ----------


def filter_label_file(src_path: Path, dst_path: Path) -> tuple[int, int, dict[int, int]]:
    """
    Returns (kept_lines, dropped_lines, per_new_id_count).
    Writes the filtered+remapped label file to dst_path. If no lines survive,
    dst_path is NOT written and (0, dropped, {}) is returned.
    """
    kept = 0
    dropped = 0
    counts: dict[int, int] = defaultdict(int)
    out_lines: list[str] = []
    try:
        for raw in src_path.read_text(encoding="utf-8").splitlines():
            raw = raw.strip()
            if not raw:
                continue
            parts = raw.split()
            if len(parts) < 5:
                dropped += 1
                continue
            try:
                old_id = int(parts[0])
            except ValueError:
                dropped += 1
                continue
            if old_id not in ID_REMAP:
                dropped += 1
                continue
            new_id = ID_REMAP[old_id]
            counts[new_id] += 1
            kept += 1
            out_lines.append(f"{new_id} " + " ".join(parts[1:]))
    except FileNotFoundError:
        return 0, 0, {}

    if out_lines:
        dst_path.parent.mkdir(parents=True, exist_ok=True)
        dst_path.write_text("\n".join(out_lines) + "\n", encoding="utf-8")
    return kept, dropped, dict(counts)


def write_data_yaml() -> Path:
    yaml_path = DST_ROOT / "data.yaml"
    lines = [
        "# Construction-PPE filtered for İşGözcü v4 (6 classes).",
        "# Generated by tests/prepare_construction_ppe_for_v4.py",
        "path: .",
        "train: images/train",
        "val: images/val",
        "test: images/test",
        "nc: 6",
        "names:",
    ]
    for cid in sorted(NEW_NAMES):
        lines.append(f"  {cid}: {NEW_NAMES[cid]}")
    yaml_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return yaml_path


def main() -> int:
    print("=" * 64)
    print("Construction-PPE → İşGözcü v4 hazırlama (11 → 6 sınıf)")
    print("=" * 64)

    if not SRC_ROOT.exists():
        print(f"[hata] Kaynak yok: {SRC_ROOT}")
        print("       Önce ZIP'i indir + çıkart.")
        return 2

    # Sanity-check the expected layout.
    for split in SPLITS:
        for sub in ("images", "labels"):
            d = SRC_ROOT / sub / split
            if not d.exists():
                print(f"[uyarı] Beklenen dizin eksik: {d}")

    DST_ROOT.mkdir(parents=True, exist_ok=True)

    # Counters
    total_orig_instances: dict[int, int] = defaultdict(int)  # by ORIGINAL id
    total_new_instances_by_split: dict[str, dict[int, int]] = {s: defaultdict(int) for s in SPLITS}
    images_kept_by_split: dict[str, int] = {s: 0 for s in SPLITS}
    images_dropped_by_split: dict[str, int] = {s: 0 for s in SPLITS}

    for split in SPLITS:
        src_img_dir = SRC_ROOT / "images" / split
        src_lbl_dir = SRC_ROOT / "labels" / split
        dst_img_dir = DST_ROOT / "images" / split
        dst_lbl_dir = DST_ROOT / "labels" / split
        if not src_img_dir.exists():
            continue
        dst_img_dir.mkdir(parents=True, exist_ok=True)
        dst_lbl_dir.mkdir(parents=True, exist_ok=True)

        # Iterate by image (some splits have stray label files we don't want).
        images = sorted([p for p in src_img_dir.iterdir() if p.suffix.lower() in (".jpg", ".jpeg", ".png")])
        print(f"\n[{split}] {len(images)} görüntü taranacak...")

        for i, img_path in enumerate(images, 1):
            label_path = src_lbl_dir / f"{img_path.stem}.txt"

            # Pre-count original-class instances for stats (independent of filtering).
            try:
                for raw in label_path.read_text(encoding="utf-8").splitlines():
                    raw = raw.strip()
                    if not raw:
                        continue
                    parts = raw.split()
                    if len(parts) < 5:
                        continue
                    try:
                        oid = int(parts[0])
                        total_orig_instances[oid] += 1
                    except ValueError:
                        continue
            except FileNotFoundError:
                pass

            new_label_path = dst_lbl_dir / f"{img_path.stem}.txt"
            kept, _dropped, per_new_count = filter_label_file(label_path, new_label_path)

            if kept == 0:
                images_dropped_by_split[split] += 1
                continue

            # Copy image
            (dst_img_dir / img_path.name).write_bytes(img_path.read_bytes())
            images_kept_by_split[split] += 1
            for new_id, n in per_new_count.items():
                total_new_instances_by_split[split][new_id] += n

            if i % 100 == 0:
                print(f"  {i}/{len(images)} işlendi (tutulan: {images_kept_by_split[split]})")

    yaml_path = write_data_yaml()

    # ---------- print + persist stats ----------
    print()
    print("Orijinal 11 sınıf instance sayısı (filtreleme öncesi):")
    for oid in sorted(ORIG_NAMES):
        keep = "↦ kept" if oid in ID_REMAP else "(drop)"
        print(f"  {oid:>2} {ORIG_NAMES[oid]:<12} {total_orig_instances.get(oid, 0):>6}  {keep}")

    print()
    print("Filtre sonrası v4 sınıf dağılımı:")
    header = f"{'class':<14}" + "".join(f"{s:>10}" for s in SPLITS) + f"{'TOPLAM':>10}"
    print(header)
    print("-" * len(header))
    warnings = []
    for cid in sorted(NEW_NAMES):
        line = f"{cid} {NEW_NAMES[cid]:<12}"
        total_for_class = 0
        for split in SPLITS:
            n = total_new_instances_by_split[split].get(cid, 0)
            line += f"{n:>10}"
            total_for_class += n
        line += f"{total_for_class:>10}"
        print(line)
        train_n = total_new_instances_by_split["train"].get(cid, 0)
        if train_n < MIN_TRAIN_SAMPLES_WARN:
            warnings.append(f"  ⚠ {NEW_NAMES[cid]}: train sadece {train_n} örnek (eşik: {MIN_TRAIN_SAMPLES_WARN})")

    print()
    print("Görüntü sayıları (annotation kalmadıysa atlandı):")
    for split in SPLITS:
        print(f"  {split:<6} kept={images_kept_by_split[split]:>5}  dropped={images_dropped_by_split[split]:>3}")

    if warnings:
        print()
        print("UYARI — düşük örnek sayısı:")
        for w in warnings:
            print(w)
    else:
        print()
        print("Tüm sınıflar yeterli örneğe sahip ✓")

    stats = {
        "splits": {
            split: {
                "images_kept": images_kept_by_split[split],
                "images_dropped": images_dropped_by_split[split],
                "instances_per_class": {
                    NEW_NAMES[cid]: total_new_instances_by_split[split].get(cid, 0)
                    for cid in sorted(NEW_NAMES)
                },
            }
            for split in SPLITS
        },
        "original_instances": {
            ORIG_NAMES[oid]: total_orig_instances.get(oid, 0)
            for oid in sorted(ORIG_NAMES)
        },
        "kept_classes": NEW_NAMES,
        "id_remap": ID_REMAP,
        "warnings": warnings,
    }
    (DST_ROOT / "stats.json").write_text(json.dumps(stats, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\nİstatistikler: {DST_ROOT / 'stats.json'}")
    print(f"data.yaml:     {yaml_path}")
    print(f"Hedef yol:     {DST_ROOT}")
    print("=" * 64)
    return 0


if __name__ == "__main__":
    sys.exit(main())
